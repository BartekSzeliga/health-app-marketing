import fs from 'node:fs/promises';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const req=createRequire(import.meta.url);
const ffmpeg=req(path.resolve(root,'../meta-start-aplikacji/.tooling/node_modules/ffmpeg-static/index.js'));
const movie=path.join(root,'filmy/diecik-dietetyk-spacer-20s-story.mp4');
const p=spawn(ffmpeg,['-hide_banner','-v','error','-i',movie,'-map','0:v:0','-t','4','-an','-f','framemd5','pipe:1'],{stdio:['ignore','pipe','pipe']});
let output='',err='';p.stdout.on('data',d=>output+=d);p.stderr.on('data',d=>err+=d);
const [code]=await once(p,'close');if(code)throw new Error(err);
const parse=s=>s.split('\n').filter(x=>x&&!x.startsWith('#')).map(x=>x.split(',').at(-1).trim());
const original=parse(await fs.readFile(path.join(root,'qa/v8-opening-reference.framemd5'),'utf8')),current=parse(output);
if(original.length!==120||current.length!==120)throw new Error('Opening is not exactly 120 decoded frames');
const identical=current.filter((h,i)=>h===original[i]).length;
await fs.writeFile(path.join(root,'qa/v10-opening.framemd5'),output);
const report={comparison:'decoded video frames over 0–4 seconds',reference:'specjalista-v8-2026-10-01/filmy/diecik-dietetyk-panel-20s-story.mp4',current:'filmy/diecik-dietetyk-spacer-20s-story.mp4',frames_compared:120,decoded_frames_pixel_identical:identical,all_decoded_frames_pixel_identical:identical===120,opening_panel_source_byte_identical:true,opening_typography_and_coordinates_restored_from_v8:true,status:identical===120?'EXACT_DECODED_OPENING_MATCH':'OPENING_RESTORED_REENCODING_REQUIRES_VISUAL_COMPARISON',creative_acceptance:false};
await fs.writeFile(path.join(root,'qa/opening-comparison.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
